#!/usr/bin/env bash
#
# Drive the phase-0 lake skeleton (DATA_LAKE_DESIGN.md §11.1).
#
#   lake-skeleton.sh up        bring the stack up and bootstrap bucket + key
#   lake-skeleton.sh seed      generate the obviously-synthetic fixture set
#   lake-skeleton.sh ingest M  load REAL records from source manifest M (#4271)
#   lake-skeleton.sh verify    run the acceptance checks (bucket + catalog)
#   lake-skeleton.sh verify-at-rest
#                              prove data on disk is envelope-encrypted (#4273)
#   lake-skeleton.sh explorer-env [check|sync]
#                              compare (or copy) the explorer's credentials
#                              into the deploy .env (system_3 #9074)
#   lake-skeleton.sh status    show containers, published ports, and disk use
#   lake-skeleton.sh down      stop the stack, keep the scratch data
#   lake-skeleton.sh destroy   stop the stack and delete every byte it owns
#
# `destroy` is the point, not an afterthought: under §11.0 this stack runs
# before encryption exists, so its safety rests on being genuinely disposable.
# If anything it wrote survives `destroy`, the guardrail has failed.
#
# All state lives under $LAKE_SKELETON_ROOT (default /scratch/lake-skeleton) —
# the scratch spindle, never /data, which is reserved for the real lake.

set -euo pipefail

ROOT="${LAKE_SKELETON_ROOT:-/scratch/lake-skeleton}"
PROJECT="aspirant-lake-skeleton"
BUCKET="${LAKE_S3_BUCKET:-lake-skeleton-bronze}"
KEY_NAME="lake-skeleton-rw"

# The explorer's read-only credentials (#2409-D4, system_3 #2542).
#
# These exist because the mediated lake bridge is only bounded if the
# CREDENTIALS are bounded. The operator authorised a mediated *read* path; a
# read-write key would make it a mediated read-write path with nothing marking
# the difference.
#
# They are issued HERE, by the bootstrap, and not by hand. Both credentials
# previously existed only as manual artifacts on one host: correct on that
# machine, absent from the repo, and silently gone after the destroy-and-
# recreate that LAKE_SKELETON.md makes an acceptance criterion. A bound that
# does not survive a rebuild is not a bound, and one that lives in a single
# host's memory cannot be reviewed.
RO_KEY_NAME="lake-skeleton-explorer-ro"
CATALOG_RO_ROLE="explorer_ro"

ENV_FILE="$ROOT/lake-skeleton.env"

SRC_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
COMPOSE_FILE="$SRC_DIR/docker-compose.lake-skeleton.yml"

# Refuse to run against the real lake's volume. This is a structural stop, not
# a warning: the whole re-sequencing in §11.0 is only safe while the skeleton
# cannot touch /data.
case "$ROOT" in
  /data|/data/*)
    echo "refusing: LAKE_SKELETON_ROOT=$ROOT is on the real lake's volume (§11.0)" >&2
    exit 1
    ;;
esac

compose() {
  docker compose -p "$PROJECT" -f "$COMPOSE_FILE" --env-file "$ENV_FILE" "$@"
}

garage_cli() {
  docker exec -e GARAGE_CONFIG_FILE=/etc/garage/garage.toml lake-skeleton-garage /garage "$@"
}

catalog_psql() {
  docker exec -i lake-skeleton-catalog \
    psql -v ON_ERROR_STOP=1 -U ducklake -d lake_catalog_skeleton "$@"
}

# Upsert a key into $ENV_FILE.
#
# NOT a bare `sed -i "s|^KEY=.*|KEY=$v|"`. That is what the file used before,
# and it silently does nothing when the key is absent — which is exactly the
# case for every env file created before this change, since seed_config only
# writes the template when the file does not already exist. The result would be
# a bootstrap that reports success while leaving the explorer with no
# credentials, on precisely the hosts that already exist.
env_set() {
  local key="$1" value="$2"
  # The value becomes a sed replacement, where `|` ends the expression and `&`
  # and `\` are special, so any of them would silently corrupt the file.
  # Every current generator emits hex; refuse rather than mangle a future one.
  case "$value" in
    *'|'* | *'&'* | *'\'*)
      echo "refusing: value for $key contains | & or \\, which env_set cannot write safely" >&2
      return 1
      ;;
  esac
  if grep -q "^${key}=" "$ENV_FILE" 2>/dev/null; then
    sed -i "s|^${key}=.*|${key}=${value}|" "$ENV_FILE"
  else
    printf '%s=%s\n' "$key" "$value" >> "$ENV_FILE"
  fi
}

seed_config() {
  mkdir -p "$ROOT"/{config,garage/meta,garage/data,catalog}

  if [ ! -f "$ROOT/config/garage.toml" ]; then
    cat > "$ROOT/config/garage.toml" <<EOF
# Generated by lake-skeleton.sh — regenerated on a fresh 'up' after 'destroy'.
# Single node, replication_factor 1: this is a disposable skeleton, and Garage's
# own docs are explicit that a single-node deployment provides no redundancy.
replication_factor = 1
metadata_dir = "/var/lib/garage/meta"
data_dir = "/var/lib/garage/data"
db_engine = "lmdb"

rpc_bind_addr = "[::]:3901"
rpc_public_addr = "127.0.0.1:3901"
rpc_secret = "$(openssl rand -hex 32)"

[s3_api]
# 0.0.0.0 inside the container only — compose publishes no host port, so this
# listener is reachable from the project's own bridge network and nowhere else.
api_bind_addr = "[::]:3900"
s3_region = "garage"
EOF
    chmod 600 "$ROOT/config/garage.toml"
  fi

  if [ ! -f "$ENV_FILE" ]; then
    cat > "$ENV_FILE" <<EOF
LAKE_SKELETON_ROOT=$ROOT
LAKE_S3_BUCKET=$BUCKET
LAKE_CATALOG_PASSWORD=$(openssl rand -hex 24)
# Filled in by 'up' once Garage issues the keys.
LAKE_S3_ACCESS_KEY=pending
LAKE_S3_SECRET_KEY=pending
# The explorer's read-only pair — read by docker-compose.yml's explorer-api.
EXPLORER_S3_ACCESS_KEY=pending
EXPLORER_S3_SECRET_KEY=pending
LAKE_CATALOG_RO_PASSWORD=pending
LAKE_CATALOG_RO_DSN=pending
EOF
    chmod 600 "$ENV_FILE"
  fi
}

wait_healthy() {
  local svc="$1" tries=0
  until [ "$(docker inspect -f '{{.State.Health.Status}}' "lake-skeleton-$svc" 2>/dev/null)" = "healthy" ]; do
    tries=$((tries + 1))
    [ "$tries" -gt 60 ] && { echo "timed out waiting for $svc" >&2; return 1; }
    sleep 2
  done
}

bootstrap_garage() {
  # A fresh Garage node has no layout, and without a layout the S3 API answers
  # nothing. Assigning it is idempotent-by-check rather than by nature: applying
  # a layout twice bumps the version, so only do it when there are no roles yet.
  if ! garage_cli layout show 2>/dev/null | grep -q "$BUCKET" && \
     ! garage_cli status 2>/dev/null | grep -qE '^\s*[0-9a-f]{16}\s+.*\s(dc1)\s'; then
    local node_id
    node_id="$(garage_cli node id -q 2>/dev/null | cut -d@ -f1)"
    if [ -n "$node_id" ] && ! garage_cli layout show 2>/dev/null | grep -q "$node_id"; then
      garage_cli layout assign -z dc1 -c 50G "$node_id" >/dev/null
      garage_cli layout apply --version 1 >/dev/null
    fi
  fi

  garage_cli bucket info "$BUCKET" >/dev/null 2>&1 || garage_cli bucket create "$BUCKET" >/dev/null

  if ! garage_cli key info "$KEY_NAME" >/dev/null 2>&1; then
    garage_cli key create "$KEY_NAME" >/dev/null
    garage_cli bucket allow --read --write "$BUCKET" --key "$KEY_NAME" >/dev/null
  fi

  # The explorer's key: --read, and deliberately no --write.
  #
  # Re-granted on every run even when the key already exists. Creation and
  # permission are separate operations in Garage, so a key that exists proves
  # nothing about what it is allowed to do — and `--read` is idempotent, so
  # asserting it costs nothing and closes the window where a key was created
  # here and widened elsewhere.
  if ! garage_cli key info "$RO_KEY_NAME" >/dev/null 2>&1; then
    garage_cli key create "$RO_KEY_NAME" >/dev/null
  fi
  garage_cli bucket allow --read "$BUCKET" --key "$RO_KEY_NAME" >/dev/null
  garage_cli bucket deny --write "$BUCKET" --key "$RO_KEY_NAME" >/dev/null 2>&1 || true

  local key_id secret ro_key_id ro_secret
  key_id="$(garage_cli key info "$KEY_NAME" --show-secret | awk '/Key ID:/ {print $3}')"
  secret="$(garage_cli key info "$KEY_NAME" --show-secret | awk '/Secret key:/ {print $3}')"
  env_set LAKE_S3_ACCESS_KEY "$key_id"
  env_set LAKE_S3_SECRET_KEY "$secret"

  ro_key_id="$(garage_cli key info "$RO_KEY_NAME" --show-secret | awk '/Key ID:/ {print $3}')"
  ro_secret="$(garage_cli key info "$RO_KEY_NAME" --show-secret | awk '/Secret key:/ {print $3}')"
  # Written under the names the main compose file reads for explorer-api, so
  # the service is bound to THIS key rather than to whatever the environment
  # happened to hold. That binding is the second half of the guarantee: issuing
  # a read-only key changes nothing if the consumer is handed a different one.
  env_set EXPLORER_S3_ACCESS_KEY "$ro_key_id"
  env_set EXPLORER_S3_SECRET_KEY "$ro_secret"
}

# SELECT-only catalog role, for the same reason and with the same history: it
# existed on one host and in no script.
bootstrap_catalog_role() {
  local pw
  pw="$(grep '^LAKE_CATALOG_RO_PASSWORD=' "$ENV_FILE" 2>/dev/null | cut -d= -f2-)"
  if [ -z "$pw" ] || [ "$pw" = "pending" ]; then
    pw="$(openssl rand -hex 24)"
    env_set LAKE_CATALOG_RO_PASSWORD "$pw"
  fi

  # Idempotent by construction: CREATE ROLE fails if it exists, so the DO block
  # branches, and the GRANTs are re-asserted every run for the same reason the
  # Garage --read is.
  catalog_psql <<SQL >/dev/null
DO \$\$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '$CATALOG_RO_ROLE') THEN
    CREATE ROLE $CATALOG_RO_ROLE LOGIN;
  END IF;
END
\$\$;
ALTER ROLE $CATALOG_RO_ROLE WITH PASSWORD '$pw';
REVOKE ALL ON SCHEMA public FROM $CATALOG_RO_ROLE;
GRANT CONNECT ON DATABASE lake_catalog_skeleton TO $CATALOG_RO_ROLE;
GRANT USAGE ON SCHEMA public TO $CATALOG_RO_ROLE;
GRANT SELECT ON ALL TABLES IN SCHEMA public TO $CATALOG_RO_ROLE;
-- Tables created later by the DuckLake catalog must inherit SELECT, or the
-- role is read-only today and blind tomorrow.
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT SELECT ON TABLES TO $CATALOG_RO_ROLE;
SQL

  env_set LAKE_CATALOG_RO_DSN \
    "postgresql://$CATALOG_RO_ROLE:$pw@lake-skeleton-catalog:5432/lake_catalog_skeleton"
}

# The write-denial proof lives in lake_skeleton_verify.py, not here.
#
# It belongs with the other acceptance checks because that is what it is: the
# claim "the explorer holds a read-only key" is exactly as strong as the
# attempt to write with it. Putting it there also keeps it on the stack's own
# client image — an earlier draft of this ran `amazon/aws-cli` via `docker run`,
# which adds a ~400MB pull to the bootstrap of a deliberately disposable
# skeleton, over a link the standing constraints call slow and lossy.
#
# Run it with: scripts/lake-skeleton.sh verify

# Layer-1 (LUKS) claim, per data directory (#4273-B1, #4525 from #4301 F7).
#
# Resolved FROM THE PATH — `findmnt -T`, which answers "what device is this
# directory actually on" — not from the hardcoded three-name ceremony list in
# scripts/luks-layer1/postcheck.sh, which answers a different question ("are
# scratch_crypt/lake_crypt/data_crypt mapped"). Those coincide for the real
# lake but never for this skeleton, whose root is deliberately plain scratch
# (§11.0): the postcheck list has no entry for it at all, so asking it here
# would silently report nothing rather than the true answer.
#
# Two things #4301 F7 found and this now does:
#   * one directory is not the lake. garage/data, garage/meta and catalog are
#     three separate compose bind mounts and can sit on three different
#     volumes; a verdict resolved from $ROOT alone would call all three
#     encrypted the day only the root is. layer1_check_all resolves each.
#   * `lsblk -no TYPE <dev>` names the device itself, so LUKS beneath LVM
#     (a `lvm` LV on a `crypt` PV — the real lake's ceremony shape) read as
#     NOT ENGAGED. `lsblk -s` walks the dependency chain upward; dm-crypt
#     anywhere in it is an engaged layer 1 for the bytes on top.
#
# layer1_check prints one PASS/FAIL/SKIP line and returns 0 (engaged), 1
# (resolution failed) or 2 (resolved but no dm-crypt in the chain) — SKIP, not
# FAIL, because an unencrypted scratch volume is not a bug in this script, but
# the caller must still keep it out of a green verdict (mirrors check 5's
# SKIP-is-never-green rule in lake_verify_at_rest.py).
layer1_check() {
  local target="$1" source chain
  source="$(findmnt -T "$target" -no SOURCE 2>/dev/null || true)"
  if [ -z "$source" ]; then
    echo "  [FAIL] layer 1: cannot resolve the device backing $target"
    return 1
  fi
  # The device and everything beneath it, top-down (e.g. "lvm crypt part disk").
  chain="$(lsblk -sno TYPE "$source" 2>/dev/null | tr '\n' ' ' | sed 's/ *$//' || true)"
  chain="${chain:-unknown}"
  case " $chain " in
    *" crypt "*)
      echo "  [PASS] layer 1: $target is backed by $source [$chain] — dm-crypt engaged in the chain"
      return 0
      ;;
  esac
  echo "  [SKIP] layer 1: $target is backed by $source [$chain], no dm-crypt in the chain — NOT ENGAGED." \
       "Layer 2 over an unlocked, unencrypted volume is a weaker claim than it appears (#4273)."
  return 2
}

# The directories the lake's bytes actually land in — the compose file's three
# bind mounts under $ROOT. Kept as one list so the check and the compose file
# are read together when either changes.
LAYER1_DATA_DIRS=(garage/data garage/meta catalog)

# Resolve layer 1 for every data directory; return the WORST result: 1 if any
# directory failed to resolve or does not exist, else 2 if any is not
# encrypted, else 0. Three PASS lines are the claim; anything less is not.
layer1_check_all() {
  local root="$1" rel dir rc worst=0 engaged=0
  for rel in "${LAYER1_DATA_DIRS[@]}"; do
    dir="$root/$rel"
    if [ ! -d "$dir" ]; then
      echo "  [FAIL] layer 1: $dir does not exist — the stack has not been bootstrapped, nothing to resolve"
      worst=1
      continue
    fi
    rc=0
    layer1_check "$dir" || rc=$?
    case "$rc" in
      0) engaged=$((engaged + 1)) ;;
      1) worst=1 ;;
      2) [ "$worst" -eq 0 ] && worst=2 ;;
    esac
  done
  echo "  layer 1: $engaged of ${#LAYER1_DATA_DIRS[@]} data directories on dm-crypt"
  return "$worst"
}

# The explorer does not read $ENV_FILE. docker-compose.yml's explorer-api
# takes its lake credentials from the deploy checkout's .env, and nothing
# carried a rebuild's fresh ones across. After the 2026-10-25 rebuild the
# explorer authenticated with the previous set for three days, and it logged
# the stale catalog password on every attempt (system_3 #9074).
DEPLOY_ENV_FILE="${ASPIRANT_DEPLOY_ENV_FILE:-$SRC_DIR/.env}"

# <deploy .env key>=<skeleton env key>
EXPLORER_ENV_MAP=(
  "EXPLORER_S3_ACCESS_KEY=EXPLORER_S3_ACCESS_KEY"
  "EXPLORER_S3_SECRET_KEY=EXPLORER_S3_SECRET_KEY"
  "LAKE_CATALOG_DSN=LAKE_CATALOG_RO_DSN"
)

env_get() {
  { grep "^$2=" "$1" 2>/dev/null || true; } | tail -n 1 | cut -d= -f2-
}

# Reports per key and never prints a value. Returns 1 on any drift.
explorer_env_check() {
  local pair dkey skey want got rc=0
  for pair in "${EXPLORER_ENV_MAP[@]}"; do
    dkey="${pair%%=*}"
    skey="${pair#*=}"
    want="$(env_get "$ENV_FILE" "$skey")"
    got="$(env_get "$DEPLOY_ENV_FILE" "$dkey")"
    if [ -z "$want" ] || [ "$want" = "pending" ]; then
      echo "  [FAIL] $skey is not issued in $ENV_FILE"
      rc=1
    elif [ "$got" = "$want" ]; then
      echo "  [ok]   $dkey matches $skey"
    elif [ -z "$got" ]; then
      echo "  [FAIL] $dkey is missing from $DEPLOY_ENV_FILE"
      rc=1
    else
      echo "  [FAIL] $dkey in $DEPLOY_ENV_FILE differs from $skey"
      rc=1
    fi
  done
  return "$rc"
}

# Copies all three or none. The backup goes under $ROOT, on the scratch volume
# beside the skeleton env, rather than as an untracked secret in the checkout.
explorer_env_sync() {
  local pair dkey skey value backup
  if [ ! -f "$DEPLOY_ENV_FILE" ]; then
    echo "refusing: $DEPLOY_ENV_FILE does not exist" >&2
    return 1
  fi
  for pair in "${EXPLORER_ENV_MAP[@]}"; do
    skey="${pair#*=}"
    value="$(env_get "$ENV_FILE" "$skey")"
    if [ -z "$value" ] || [ "$value" = "pending" ]; then
      echo "refusing: $skey is not issued in $ENV_FILE; run 'up' first" >&2
      return 1
    fi
    # Checked here as well as in env_set, so a refusal comes before any write.
    case "$value" in
      *'|'* | *'&'* | *'\'*)
        echo "refusing: $skey contains | & or \\, which env_set cannot write safely" >&2
        return 1
        ;;
    esac
  done
  # The backup holds every service's secrets, not just these three. Create it
  # 600 from the start, rather than cp-then-chmod (which leaves it at the
  # source's mode in between), and keep only the newest copy.
  backup="$ROOT/deploy-env.bak-$(date -u +%Y%m%dT%H%M%SZ)"
  rm -f "$ROOT"/deploy-env.bak-*
  install -m 600 "$DEPLOY_ENV_FILE" "$backup"
  local skeleton_env="$ENV_FILE"
  for pair in "${EXPLORER_ENV_MAP[@]}"; do
    dkey="${pair%%=*}"
    skey="${pair#*=}"
    value="$(env_get "$skeleton_env" "$skey")"
    ENV_FILE="$DEPLOY_ENV_FILE" env_set "$dkey" "$value"
  done
  # The deploy .env was found at 644 (security review, #9074 c55779).
  chmod 600 "$DEPLOY_ENV_FILE"
  echo "explorer credentials copied into $DEPLOY_ENV_FILE (previous copy: $backup)"
  echo "next: docker compose --profile explorer up -d explorer-api"
}

# Test-mode escape hatch: source this file with ASPIRANT_LAKE_SKELETON_LIB=1 to
# get the pure helpers without dispatching a verb. Mirrors the same hatch in
# auto-pull.sh so the two test suites read alike.
if [ "${ASPIRANT_LAKE_SKELETON_LIB:-0}" = "1" ]; then
  return 0 2>/dev/null || true
fi

case "${1:-}" in
  up)
    seed_config
    compose up -d garage catalog
    wait_healthy catalog
    # Garage reports unhealthy until its layout is applied, so bootstrap runs
    # against a started-but-not-yet-healthy node rather than waiting first.
    sleep 5
    bootstrap_garage
    wait_healthy garage
    bootstrap_catalog_role
    echo "lake skeleton up — bucket '$BUCKET' on $ROOT (credentials in $ENV_FILE)"
    echo "explorer read-only credentials issued: '$RO_KEY_NAME' + catalog role '$CATALOG_RO_ROLE'"
    echo "their read-only-ness is PROVEN by 'verify', not asserted here — run it next"
    echo "explorer credentials in $DEPLOY_ENV_FILE:"
    explorer_env_check ||
      echo "  stale: run 'lake-skeleton.sh explorer-env sync', then recreate explorer-api"
    echo "next: 'lake-skeleton.sh seed' to generate fixtures, then 'verify'"
    ;;

  seed)
    compose --profile client run --rm duckdb /work/fixtures.py
    ;;

  ingest)
    # The real-data ingest runner (#4271 / #4238-B1). Separate verb, separate
    # script: `seed` writes obviously-synthetic fixtures and is safe to re-run
    # anywhere; this one writes the operator's actual bytes and is not.
    #
    # The manifest's own directory is mounted read-only at /source, so relative
    # record paths inside the manifest resolve exactly as they do on the host.
    # Read-only is not a formality: an ingest that could write to the source
    # tree could damage the only copy of the data it is reading.
    manifest="${2:-}"
    if [ -z "$manifest" ] || [ ! -f "$manifest" ]; then
      echo "usage: lake-skeleton.sh ingest <manifest.json> [--dry-run]" >&2
      exit 1
    fi
    shift 2
    manifest_dir="$(cd "$(dirname "$manifest")" && pwd)"
    # Exported rather than prefixed onto the call: `compose` is a shell
    # function here, and a prefix assignment on a function is not reliably
    # exported to the docker process that has to interpolate it.
    export LAKE_INGEST_SOURCE="$manifest_dir"
    compose --profile client run --rm duckdb \
      /work/ingest.py "/source/$(basename "$manifest")" "$@"
    ;;

  verify)
    compose --profile client run --rm duckdb /work/verify.py
    ;;

  verify-at-rest)
    # One combined verdict over both layers (#4273-B1): layer 1 (LUKS) is
    # checked HERE, on the host, as this user — cryptsetup/findmnt/lsblk see
    # the block device and dm-crypt state the client container cannot; layer 2
    # (the catalog + object-store claims) runs INSIDE the client container,
    # via the #4299 checker, against LAKE_CATALOG_DSN and Garage. One script
    # cannot make both claims — see #4273-B1's task body — so this verb runs
    # both and combines their exit codes rather than picking one.
    echo "=== layer 1 (LUKS) ==="
    layer1_rc=0
    layer1_check_all "$ROOT" || layer1_rc=$?
    echo
    echo "=== layer 2 (catalog + object store, #4299) ==="
    layer2_rc=0
    # Build the client image as its own step (#4475, was a pinned-digest pull
    # per #4525/#4301 F6): the duckdb service builds locally from
    # Dockerfile-LakeDuckDB, so `compose run` would build it inline and a build
    # failure would surface as "layer 2 failed" with the build noise mixed into
    # the harness's report. Building first makes "the image could not be built"
    # its own sentence, distinct from "the harness ran and said NOT GREEN" —
    # both are NOT GREEN, but only one of them is a finding about the lake.
    if compose --profile client build -q duckdb; then
      compose --profile client run --rm duckdb /work/verify_at_rest.py || layer2_rc=$?
    else
      echo "  [FAIL] layer 2: the client image could not be built from Dockerfile-LakeDuckDB" \
           "— the harness did not run, so nothing about the lake was verified"
      layer2_rc=1
    fi
    echo
    echo "=== combined verdict ==="
    if [ "$layer1_rc" -eq 0 ] && [ "$layer2_rc" -eq 0 ]; then
      echo "  GREEN — layer 1 engaged and layer 2's catalog/object-store checks (0-7, #4299/#4524) are green."
      exit 0
    fi
    [ "$layer1_rc" -ne 0 ] && echo "  layer 1: NOT GREEN (see above)"
    [ "$layer2_rc" -ne 0 ] && echo "  layer 2: NOT GREEN (see above)"
    echo "  NOT GREEN"
    exit 1
    ;;

  explorer-env)
    case "${2:-check}" in
      check) explorer_env_check ;;
      sync) explorer_env_sync ;;
      *)
        echo "usage: lake-skeleton.sh explorer-env [check|sync]" >&2
        exit 1
        ;;
    esac
    ;;

  status)
    compose ps
    echo
    echo "published host ports (expect none):"
    docker ps --filter "label=com.docker.compose.project=$PROJECT" --format '{{.Names}}: {{.Ports}}'
    echo
    du -sh "$ROOT" 2>/dev/null || echo "$ROOT does not exist"
    ;;

  down)
    compose down
    echo "stack stopped; data retained at $ROOT"
    ;;

  destroy)
    compose down -v --remove-orphans || true
    # Postgres and Garage write as root/postgres inside the containers, so the
    # scratch tree is not owned by the invoking user.
    sudo rm -rf "$ROOT"
    echo "destroyed: containers, volumes, and $ROOT"
    ;;

  *)
    sed -n '3,19p' "${BASH_SOURCE[0]}"
    exit 1
    ;;
esac
